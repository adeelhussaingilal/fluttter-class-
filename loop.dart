void main() {
  // FOR LOOP
  print("For Loop:");

  for (int i = 1; i <= 5; i++) {
    print(i);
  }

  // WHILE LOOP
  print("\nWhile Loop:");

  int j = 1;

  while (j <= 5) {
    print(j);
    j++;
  }

  // DO-WHILE LOOP
  print("\nDo-While Loop:");

  int k = 1;

  do {
    print(k);
    k++;
  } while (k <= 5);
}
